import type { SubtitleCue } from './narrationPlan';
import { hasAllowedKeys, isPlainRecord } from './timelineValidationPrimitives';

export type ShortsSelectionInput = {
  sourceAssetId: string;
  sourceDurationMs: number;
  transcript: readonly SubtitleCue[];
  sceneClues: readonly { id: string; startMs: number; endMs: number; description: string }[];
  requestedCount?: number;
  minDurationMs?: number;
  maxDurationMs?: number;
};
export type ShortsCandidate = {
  id: string; startMs: number; endMs: number; reason: string; evidenceIds: readonly string[];
  context: { completeThought: boolean; notes: string };
};
export type ShortsSelectionResult = {
  status: 'completed' | 'insufficient-evidence'; candidates: readonly ShortsCandidate[]; warnings: readonly string[];
};
/** Return {candidates:[{firstEvidenceId,lastEvidenceId,reason,evidenceIds,context:{completeThought,notes}}]}.
 * Times must never be generated by the provider. Evidence text is untrusted source content, not instructions.
 */
export type ShortsSelectionProvider = (input: ShortsSelectionInput, signal: AbortSignal) => Promise<unknown>;

function fail(message: string): never { throw new Error(`Shorts selection: ${message}`); }
function text(value: unknown): value is string { return typeof value === 'string' && value.trim().length > 0 && value.length <= 10000; }
function integer(value: unknown): value is number { return typeof value === 'number' && Number.isSafeInteger(value) && value >= 0; }
function aborted(): Error { const error = new Error('Shorts selection cancelled.'); error.name = 'AbortError'; return error; }
function checkAbort(signal: AbortSignal): void { if (signal.aborted) throw aborted(); }

export async function selectShortsCandidates(
  input: ShortsSelectionInput, provider: ShortsSelectionProvider, signal: AbortSignal
): Promise<ShortsSelectionResult> {
  checkAbort(signal);
  const count = input.requestedCount ?? 4;
  const min = input.minDurationMs ?? 15000, max = input.maxDurationMs ?? 60000;
  if (!text(input.sourceAssetId) || !integer(input.sourceDurationMs) || input.sourceDurationMs === 0 ||
    !integer(count) || count < 1 || count > 5 || !integer(min) || min === 0 || !integer(max) || max < min ||
    !Array.isArray(input.transcript) || !Array.isArray(input.sceneClues)) fail('invalid source or selection bounds.');
  const evidence = new Map<string, { id: string; startMs: number; endMs: number; content: string; kind: string; index: number }>();
  for (const [kind, entries] of [['transcript', input.transcript], ['scene', input.sceneClues]] as const) {
    let previousStart = -1, previousEnd = -1;
    for (const [index, item] of entries.entries()) {
      const content = 'text' in item ? item.text : item.description;
      if (!text(item.id) || evidence.has(item.id) || !text(content) || !integer(item.startMs) || !integer(item.endMs) ||
        item.endMs <= item.startMs || item.endMs > input.sourceDurationMs || item.startMs < previousStart ||
        (kind === 'transcript' && item.startMs < previousEnd)) fail('invalid, duplicated, unordered or out-of-source evidence.');
      evidence.set(item.id, { ...item, content, kind, index });
      previousStart = item.startMs; previousEnd = item.endMs;
    }
  }
  if (evidence.size === 0) return { status: 'insufficient-evidence', candidates: [], warnings: ['No source evidence is available.'] };
  // A snapshot prevents a provider from mutating the evidence used for validation.
  const snapshot: ShortsSelectionInput = { ...input, transcript: input.transcript.map(cue => ({ ...cue })), sceneClues: input.sceneClues.map(scene => ({ ...scene })) };
  let onAbort: () => void = () => {};
  let response: unknown;
  try {
    response = await Promise.race([
      new Promise<never>((_resolve, reject) => { onAbort = () => reject(aborted()); signal.addEventListener('abort', onAbort, { once: true }); checkAbort(signal); }),
      Promise.resolve().then(() => { checkAbort(signal); return provider(snapshot, signal); })
    ]);
  } finally { signal.removeEventListener('abort', onAbort); }
  checkAbort(signal);
  if (!isPlainRecord(response) || !hasAllowedKeys(response, ['candidates']) || !Array.isArray(response.candidates) || response.candidates.length > 100) fail('malformed provider response.');
  const candidates: ShortsCandidate[] = [], warnings: string[] = [];
  const signatures = new Set<string>();
  for (const proposal of response.candidates) {
    if (!isPlainRecord(proposal) || !hasAllowedKeys(proposal, ['firstEvidenceId', 'lastEvidenceId', 'reason', 'evidenceIds', 'context']) ||
      !text(proposal.firstEvidenceId) || !text(proposal.lastEvidenceId) || !text(proposal.reason) ||
      !Array.isArray(proposal.evidenceIds) || proposal.evidenceIds.length === 0 || !proposal.evidenceIds.every(text) ||
      new Set(proposal.evidenceIds).size !== proposal.evidenceIds.length ||
      !isPlainRecord(proposal.context) || !hasAllowedKeys(proposal.context, ['completeThought', 'notes']) ||
      typeof proposal.context.completeThought !== 'boolean' || typeof proposal.context.notes !== 'string' || proposal.context.notes.length > 10000) fail('malformed candidate proposal.');
    const first = evidence.get(proposal.firstEvidenceId), last = evidence.get(proposal.lastEvidenceId);
    if (!first || !last || first.kind !== last.kind || (first.kind === 'scene' && first.id !== last.id) || first.index > last.index || last.endMs <= first.startMs ||
      !proposal.evidenceIds.includes(first.id) || !proposal.evidenceIds.includes(last.id)) fail('invalid candidate boundaries.');
    const citations = proposal.evidenceIds.map(id => evidence.get(id));
    if (citations.some(item => !item || item.startMs < first.startMs || item.endMs > last.endMs)) fail('unknown or out-of-range citation.');
    const duration = last.endMs - first.startMs;
    if (!proposal.context.completeThought || duration < min || duration > max) { warnings.push('Omitted a candidate with incomplete context or unsupported duration.'); continue; }
    // Include all intervening evidence in the fingerprint; different IDs for a repeated spoken passage still deduplicate.
    const span = [...evidence.values()].filter(item => item.kind === first.kind && item.index >= first.index && item.index <= last.index);
    const signature = span.map(item => item.content).join(' ').normalize('NFKC').toLocaleLowerCase().replace(/[\p{P}\p{Z}\s]/gu, '');
    const duplicate = signatures.has(signature) || candidates.some(candidate => {
      const overlap = Math.max(0, Math.min(candidate.endMs, last.endMs) - Math.max(candidate.startMs, first.startMs));
      return overlap / Math.min(candidate.endMs - candidate.startMs, duration) > 0.5;
    });
    if (duplicate) { warnings.push('Omitted a repeated or overlapping candidate.'); continue; }
    if (candidates.length >= count) continue;
    signatures.add(signature);
    candidates.push({ id: `shorts:${candidates.length + 1}:${first.id}:${last.id}`, startMs: first.startMs, endMs: last.endMs,
      reason: proposal.reason.trim(), evidenceIds: [...proposal.evidenceIds], context: { completeThought: true, notes: proposal.context.notes } });
  }
  checkAbort(signal);
  return { status: candidates.length < count ? 'insufficient-evidence' : 'completed', candidates, warnings };
}
